-- V25: place_stats.calculated_at을 NULL 허용으로 바꾼다.
--
-- 이 컬럼의 뜻은 "마지막 배치가 이 행을 정산한 기준 시각"이다. 2026-07-31에 이벤트 증분
-- (PlaceStatsIncrementListener)이 들어오면서, 배치가 아직 닿지 않은 장소에 북마크·리뷰가 먼저
-- 도달해 증분이 행을 만드는 경로가 생겼다. 그 행은 "아직 한 번도 정산된 적 없음"이라는 상태인데,
-- NOT NULL이라 뭐라도 넣어야 해서 처음엔 epoch('1970-01-01')를 센티널로 썼다.
--
-- 센티널을 걷어내는 이유:
--   1. 이 컬럼을 읽는 애플리케이션 코드가 없다. 남은 용도는 배치 지연을 사람이 관측하는 것뿐이고,
--      그 관측은 집계로 한다 — MIN(calculated_at)이 "가장 오래된 세대"다. epoch 행이 하나라도
--      있으면 그 값이 영구히 1970년으로 고정돼 지표가 죽는다. NULL은 집계에서 자동으로 빠진다.
--   2. "없음"을 표현하는 수단이 언어에 이미 있는데 매직 상수를 새로 정의할 이유가 없다.
--      대시보드에서 1970년을 본 사람은 그것을 버그로 읽는다.
--
-- 안전성: 기존 행은 전부 배치가 실제 기준 시각으로 채운 값이라 이 ALTER로 변하는 값이 없다.
-- NULL을 넣는 주체는 앞으로의 증분 INSERT뿐이고, 다음 배치가 실제 시각으로 덮는다.
-- place_stats는 장소당 1행(현재 수천 행)이라 ALTER 비용도 무시할 수준이다.
ALTER TABLE place_stats
    MODIFY calculated_at DATETIME(6) NULL;
