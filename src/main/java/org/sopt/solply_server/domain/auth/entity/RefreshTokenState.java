package org.sopt.solply_server.domain.auth.entity;

/**
 * refresh 행이 지금 무엇인지. <b>컬럼이 아니라 시각의 함수다</b> — 저장하지 않는 이유는
 * 저장하는 순간 시간이 흐를 때마다 갱신해 줄 사람이 필요해지고, 갱신되지 않은 행이 곧
 * 거짓말이 되기 때문이다.
 *
 * <p>판정 순서가 곧 의미다. 폐기가 만료보다 앞서는 것은 <b>"만료돼서 못 쓴다"와 "폐기돼서 못
 * 쓴다"가 다른 사건</b>이기 때문이다 — 전자는 재로그인, 후자는 재사용 감지의 근거다.
 */
public enum RefreshTokenState {

    /** 폐기됨. 로그아웃·탈퇴·재사용 감지로 끊긴 토큰. */
    REVOKED,

    /** JWT exp가 지났다. 공격의 신호가 아니다 — 그냥 다시 로그인하면 된다. */
    EXPIRED,

    /** 아직 회전하지 않은 살아 있는 토큰. 회전의 유일한 정상 입력이다. */
    ACTIVE,

    /** 회전됐지만 유예가 남았다. 같은 refresh 문자열을 한 번 더 돌려준다. */
    GRACE,

    /** 회전됐고 유예도 끝났다. <b>이 토큰으로 들어온 요청이 재사용 판정의 근거다.</b> */
    GRACE_ENDED
}
