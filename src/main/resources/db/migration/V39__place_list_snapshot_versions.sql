-- V39: 목록 스냅샷의 회차 번호를 발급하는 테이블. 데이터가 아니라 "번호 발급소"다.
--
-- 빌드 하나가 끝날 때 한 줄을 insert 하고, 돌려받은 AUTO_INCREMENT id가 그 사진의 버전이 된다.
-- 커서(v6)가 그 번호를 싣고 다니며 다음 페이지가 같은 회차의 배열에서 이어지게 하고, 홀더는
-- "받은 번호가 지금 최신보다 크면 채택"이라는 단조 가드로 늦게 도착한 낡은 사진을 걸러낸다.
--
-- 지금까지 버전은 빌드가 끝난 밀리초 시각이었다. 빌더가 하나인 동안은 그것으로 충분했지만,
-- 앱 인스턴스가 둘 이상이 되면 빌더도 둘 이상이 된다(어드민 요청을 받은 인스턴스 + 타이머
-- 리더). 그때 시계가 느린 인스턴스가 더 새 데이터로 지은 사진이 작은 번호를 달고 "낡은 버전"
-- 으로 거절된다. 발급을 한 곳으로 좁히면 시계 차이와 무관하게 번호가 단조다. Redis INCR도
-- 같은 일을 하지만 Redis가 비워지면 번호가 1부터 다시 시작해 같은 거절이 난다.
-- 상세: docs/design/2026-09-09-admin-display-view-split.md §4-5
--
-- ⚠️ 컬럼을 늘리지 말 것. 이 테이블이 하는 일은 번호를 하나 내주는 것뿐이고, 사진의 내용은
--    어디에도 저장되지 않는다(인스턴스의 힙에만 있다). 무엇을 지었는지 남기고 싶으면 그 자리는
--    재빌드 로그다.
--
-- 행을 지우지 않는다. 재빌드는 10분 타이머와 어드민 커밋 훅이라 하루 수백 행이고, id는
-- AUTO_INCREMENT라 행을 지워도 다음 번호가 되감기지 않는다. 정리할 값이 없다.
CREATE TABLE place_list_snapshot_versions
(
    id        BIGINT      NOT NULL AUTO_INCREMENT,
    issued_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '번호를 내준 시각. 발급 순서는 id가 정하며 이 값은 운영 관찰용이다',

    PRIMARY KEY (id)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4;
