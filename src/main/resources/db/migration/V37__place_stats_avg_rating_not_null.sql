-- V37: avg_rating을 NOT NULL DEFAULT 0으로 조인다. 리뷰가 없는 장소도 평점순 목록에 실린다.
--
-- ⚠️ V36의 "평점순은 avg_rating IS NOT NULL 행만 본다" 문단은 이 결정으로 대체됐다. 하루 만에
--    뒤집힌 것이 맞고, 뒤집은 것은 기술이 아니라 프로덕트 판단이다 — "리뷰가 아직 없는 장소는
--    평점순 목록에서 아예 보이지 않는다"가 화면에서 받아들여지지 않았다. 새 스펙은
--    **리뷰 0건 장소를 평점 0으로 보고 평점순 맨 뒤에 놓는다**이다. V36 파일은 그대로 둔다 —
--    당시의 판단과 그 근거는 그 자리에 남아 있어야 이 뒤집힘도 읽힌다.
--
-- 스펙을 바꾸는 방법이 둘이었다.
--   (a) 조회에서 COALESCE(avg_rating, 0)으로 정렬한다. 저장은 그대로 NULL을 쓴다.
--   (b) 저장을 NOT NULL DEFAULT 0으로 바꾼다. 조회는 컬럼을 그대로 읽는다.
-- (a)는 정렬식이 컬럼이 아니라 **식**이 되는 순간 idx_place_stats_town_rating(V36)의 선두
-- 프리픽스가 성립하지 않아 인덱스가 정렬을 못 만든다 — 필터를 통과한 전 행에 filesort가 붙고,
-- 그 인덱스를 세운 이유가 통째로 사라진다. 그래서 (b)다.
--
-- **0을 "리뷰 없음"의 값으로 쓸 수 있는 근거는 척도에 있다.** place_reviews.rating은 CHECK
-- (rating BETWEEN 1 AND 5)로 1~5만 담기고(V22), 평균이 그 범위 밖으로 나갈 수 없으므로 실제 평균은
-- 결코 0이 아니다. 즉 0은 "리뷰가 한 건도 없다"와만 대응한다 — 두 뜻이 겹치는 값이 아니다.
-- ⚠️ rating의 하한을 0으로 내리는 변경이 언제든 이 전제를 깬다. 그 CHECK를 건드릴 때 여기를 함께 볼 것.
--
-- 커서가 이 변경의 실익이다. NULL이던 시절에는 seek 조건의 NULL 비교가 전부 NULL이라 그 행들이
-- 첫 페이지 뒤로 조용히 사라졌고(V36이 술어로 끊은 이유), 이제는 모든 행에 실값이 있어 0점 동점
-- 구간도 (평점, 리뷰 수, place_id) 세 겹 seek이 그대로 가른다. 리뷰 0건은 리뷰 수도 0이라
-- 그 구간의 타이브레이크는 결국 place_id ASC 하나로 결정된다.
--
-- 표시 계약은 바뀌지 않는다 — 응답의 avgRating은 리뷰 0건일 때 여전히 null이다. 저장은 정렬을
-- 위한 내부 표현이고, "평점 0점"과 "아직 평가가 없다"를 화면에서 구분하는 규칙은 그대로다
-- (PlacePreviewDto javadoc).

-- 백필이 먼저다. NOT NULL로 바로 조이면 기존 NULL 행이 strict 모드에서 거부되거나(엄밀히는
-- ALTER가 실패한다), 완화된 모드에서 암묵 기본값이 조용히 들어앉는다 — V34의 created_at과 같은 순서다.
UPDATE place_stats
SET avg_rating = 0
WHERE avg_rating IS NULL;

-- ⚠️ 이 MODIFY는 avg_rating을 담은 인덱스 다섯(V34의 둘 + V36의 셋)을 함께 재구축하므로 테이블
--    복사가 일어난다. 지금 place_stats는 장소 수만큼의 행(수천)이라 순간이지만, 규모가 커진 뒤
--    같은 성질의 ALTER를 낼 때는 온라인 DDL 가능 여부를 먼저 확인할 것.
ALTER TABLE place_stats
    MODIFY COLUMN avg_rating DECIMAL(3, 2) NOT NULL DEFAULT 0
        COMMENT '표시용 평균 평점. 리뷰 0건이면 0 — 척도가 1~5라 0은 "리뷰 없음"과만 대응한다 (V37)';
