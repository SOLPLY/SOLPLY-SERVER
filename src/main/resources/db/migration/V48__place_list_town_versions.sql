-- V48: 목록의 정합성 단위를 "전역 한 번호"에서 "동네마다 한 번호"로 좁힌다.
--
-- V46의 place_list_snapshot_metadata는 전 동네가 한 줄을 나눠 쓴다. 그래서 강남의 장소 하나가
-- 바뀌면 마포를 보고 있던 스크롤까지 끊겼고, 인스턴스는 조회되지도 않은 동네까지 전량을 다시
-- 지어야 했다. 여기서는 바뀐 동네의 번호만 오른다.
--
-- ⚠️ 번호는 동네마다 하나다. (revision, cursor_version) 두 번호를 동네별로 복제하지 않는다.
--    "다시 지을 것이 있나"와 "커서를 계속 써도 되나"를 나눌 이유가 사라졌기 때문이다 — 재적재는
--    조회된 동네에만 일어나고, 표시값만 바뀐 수정은 아예 이 번호를 올리지 않는다
--    (다음 성공한 정기 전체 배치가 처리 대상 동네를 통째로 올리고, 그 뒤 그 동네에 요청이 와서
--    적재가 성공했을 때 표시값이 반영된다).
--
-- ⚠️ 행이 없는 동네는 version 0으로 읽는다. 여기서 시딩하지 않는 이유는 동네가 나중에도
--    만들어지기 때문이다 — 어느 동네든 첫 bump가
--    INSERT ... ON DUPLICATE KEY UPDATE version = version + 1 로 자기 행을 만든다. 그 한 문장이
--    원자적이고 행마다 단조라, 시딩 여부와 무관하게 "번호가 오르면 이전 번호의 탐색은 끝났다"가
--    성립한다.
--
-- ⚠️ 번호는 "값이 바뀌었다"는 표시가 아니라 새 탐색 세대이자 무효화 경계다. 값이 그대로여도
--    성공한 정기 전체 배치는 처리 대상 동네를 통째로 올린다 — 이름·썸네일만 바뀐 동네가 갱신
--    대상에서 영구히 빠지지 않게 하려는 것이다. 그래서 번호가 올랐다고 그 동네의 표시값이 이미
--    갈렸다는 뜻은 아니다. 표시값은 배치가 성공한 뒤 그 동네를 실제로 다시 적재했을 때 반영된다.
--
-- ⚠️ 컬럼을 늘리지 말 것. 상태값·구버전 보관·TTL·별도 revision은 채택하지 않은 대안이다.
--    허용 판정은 언제나 "커서가 싣고 온 번호 == 지금 번호"다.
-- 상세: docs/design/2026-09-21-place-list-town-cache.md
CREATE TABLE place_list_town_versions
(
    town_id    BIGINT      NOT NULL,
    version    BIGINT      NOT NULL DEFAULT 1 COMMENT '이 동네의 탐색 대상/필터/순서가 바뀔 때마다 오른다',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),

    PRIMARY KEY (town_id)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4;

-- 커서 포맷은 v7(전역 번호 하나)과 v8(동네별 번호 목록)을 둘 다 디코딩한다. v7 토큰이 거부되는
-- 것이 아니라, 정적 5축이 새 동네 경로로 가면서 범위 표현이 G(전역 회차)에서 T(동네별 번호)로
-- 바뀌어 옛 정적 커서가 범위 비교에서 만료된다. 거리순과 북마크 검색은 전역 경로에 그대로 남아
-- v7 토큰으로 계속 이어진다 — 그쪽 스크롤을 일괄 만료시키지 않는다.
--
-- 옮겨 담을 번호도 없다. 여기서 행을 만들지 않고, 행이 없는 동네는 읽을 때 version 0으로 본다.
