-- place_tag의 태그 방향 인덱스를 (tag_id)에서 (tag_id, place_id)로 바꾼다.
--
-- InnoDB 세컨더리 인덱스의 리프에는 "인덱스 컬럼 + PK"만 실린다. place_tag의 PK가 대리키 id이므로
-- idx_place_tag_tag_id의 실체는 (tag_id, id)이고 place_id가 없다. 그런데 이 인덱스의 유일한 용도가
-- "태그로 장소를 찾기"라, 정작 필요한 place_id를 얻으려면 엔트리마다 클러스터드 인덱스로 한 번 더
-- 내려가야 한다. 반대 방향인 uk_place_tag_place_tag (place_id, tag_id)는 두 컬럼이 다 있어 이미
-- 커버링이다 — 한쪽만 재방문을 내는 비대칭 상태였다.
--
-- 실측(docs/perf/2026-08-10-place-tag-covering-index.md): 같은 1,146행을 내보내는 노드가
-- Index lookup 0.717ms에서 Covering index lookup 0.157ms로 4.6배 줄었다. 사라진 몫을 행당으로
-- 나누면 0.49us인데, 같은 트리의 명시적 단건 PK 조회 단가(0.69~0.82us)와 같은 자릿수다 —
-- 숨어 있던 것이 그 재방문이 맞다는 교차 확인이다. 시 단위 조회 8칸이 전부 1.2~1.5배 좋아졌고
-- 주도 테이블은 한 칸도 바뀌지 않았다.
--
-- ⚠️ 감수하는 것이 하나 있다. 태그 경로가 싸지면 옵티마이저가 그쪽으로 기운다.
--    최신순·동네 1곳·`바/술집`(연결 185곳)에서 주도 테이블이 지역에서 태그로 뒤집히고, 역방향
--    인덱스 스캔이 공짜로 주던 created_at DESC 순서를 잃어 Sort 노드가 새로 생긴다
--    (0.172 -> 0.352ms). 지역 후보 100 < 태그 후보 185라 이 뒤집힘은 틀린 선택인데, 옵티마이저는
--    오히려 더 싸다고 봤다(추정 비용 115 -> 91.2). 정렬을 공짜로 얻는 이점이 비용 모델에 안 잡힌다.
--    캠페인의 사전 등록 조건("어떤 조합도 나빠지지 않는다")이 이 한 칸에서 깨지는 것을 알고,
--    절대 손해가 +0.18ms인 반면 인덱스 형태의 정합성은 남는다고 보아 채택한다.
--    인기순은 같은 입력에서 뒤집히지 않았다 — place_stats 인덱스가 표시값까지 덮어 지역 주도의
--    이점이 더 크기 때문으로 읽었으나, 비용 계수까지 확인하지는 않았다.
--
-- 주의: fk_place_tag_tag가 tag_id 선두 인덱스를 요구하므로 새 인덱스를 먼저 만들고 옛 것을 지운다.
--
-- 함께 지우고 싶어지는 것 하나를 남겨 둔다. idx_place_tag_place_id (place_id)는
-- uk_place_tag_place_tag의 프리픽스와 완전히 겹쳐 중복이다. 그러나 이 마이그레이션에서 같이 지우면
-- 회귀가 났을 때 어느 변경 탓인지 가를 수 없다. 재보지 않은 변경을 잰 변경에 묶지 않는다.
CREATE INDEX idx_place_tag_tag_place
    ON place_tag (tag_id, place_id);
DROP INDEX idx_place_tag_tag_id ON place_tag;
