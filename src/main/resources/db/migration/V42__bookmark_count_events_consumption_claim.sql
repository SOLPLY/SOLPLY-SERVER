-- V42: 북마크 아웃박스의 소비 경계를 "전량 읽기"에서 "표식 찍기"로 바꾼다.
--
-- 지금까지 소비자는 SELECT ... FOR UPDATE로 전표 전량을 JVM으로 읽어 Map에 접고, 그 결과로
-- place_stats를 고친 뒤 읽은 id 목록으로 지웠다. 접힌 결과는 장소 수뿐인데 그 앞 단계가 전부
-- 이벤트 수에 비례했다. 한 회차가 자기 표식(UUID)을 전표에 찍으면 그 뒤의 집계·삭제가 표식
-- 하나로 좁혀지고, 접는 일은 DB의 GROUP BY가 한다.
-- 상세: docs/design/2026-09-12-stats-commit-snapshot-and-db-delta.md
--
-- ⚠️ 이 칸은 "상태"가 아니라 "이번 회차의 것"이라는 표식이다. claim·집계·적용·삭제가 한
--    트랜잭션이라, 롤백하면 표식도 함께 사라지고 커밋하면 그 행들은 같은 트랜잭션에서 이미
--    지워졌다. 즉 표식이 커밋된 채로 남는 상태가 존재하지 않는다 — PROCESSING 같은 상태값도,
--    lease 만료 시각도, 남은 표식을 회수하는 배치도 필요 없다. 여기에 재시도 횟수·워커 id·처리
--    단계를 담기 시작하면 그 셋이 전부 필요해진다.
--
-- ⚠️ V38이 "보조 인덱스도 FK도 두지 않는 것이 이 테이블의 계약"이라고 적은 자리를 여기서
--    고쳐 쓴다. 그 근거는 "쓰기 경로가 INSERT 하나로 끝나야 한다"였고, 이제 그 INSERT가 보조
--    인덱스 항목도 하나 쓴다. 소비 쪽도 전표마다 UPDATE 한 번(undo/redo 포함)이 늘었다.
--    받아들인 대가다 — 대신 전표와 id 목록이 JVM에 올라오지 않는다. 인덱스가 없으면 집계와
--    삭제가 매번 테이블 풀 스캔이 되어 바꾼 이유가 사라진다. 인덱스를 더 늘리지는 말 것.
--
-- ⚠️ id 범위 삭제 금지는 그대로다. 이번 회차가 지우는 대상의 근거는 표식이지 id 범위가 아니다
--    (근거는 V38 주석: auto_increment는 커밋 순서를 보장하지 않는다).
--
-- CHAR(36)은 이 저장소의 UUID 규약이다(V41의 family_id·jwt_id·state). 값은 소비 트랜잭션이
-- 그 자리에서 짓고 커밋 뒤에는 남지 않으므로 발급 테이블도 순번도 필요 없다.
ALTER TABLE bookmark_count_events
    ADD COLUMN consumption_id CHAR(36) NULL COMMENT '이번 소비 회차의 표식. 회차 트랜잭션 안에서만 존재한다',
    ADD INDEX idx_bookmark_count_events_consumption (consumption_id);
